    <h2 id="cookies">8. Cookies, баннер согласия и аналитика</h2>

    <h3>8.1. Что такое cookie</h3>
    <p>Cookie — небольшие фрагменты данных, которые сохраняются в браузере при посещении сайта. Они могут быть необходимыми для работы сайта либо использоваться для статистики и улучшения сервиса.</p>

    <h3>8.2. Необходимые (технические) cookie</h3>
    <p>Без них сайт не сможет корректно работать. Они устанавливаются на основании законного интереса Оператора в обеспечении безопасности и работоспособности сервиса и <strong>не требуют согласия</strong> через cookie-баннер. К ним относятся, в частности:</p>
    <ul>
        <li>cookie сессии Laravel (идентификатор сессии) — поддержка авторизации в админ-панели и работы форм;</li>
        <li>cookie <code>XSRF-TOKEN</code> — защита от межсайтовой подделки запросов (CSRF);</li>
        <li>иные строго необходимые технические cookie платформы или хостинга.</li>
    </ul>
    <p>Срок хранения: как правило, до окончания сессии браузера или в пределах срока, заданного платформой (обычно до нескольких часов / суток для сессии).</p>

    <h3>8.3. Механизм cookie-баннера</h3>
    <p>Если на сайте подключена веб-аналитика через Google Tag Manager (задаётся идентификатор контейнера), при первом визите отображается баннер с выбором:</p>
    <ul>
        <li><strong>«Принять»</strong> — даётся согласие на загрузку аналитических / маркетинговых скриптов (GTM и тегов внутри контейнера). Выбор сохраняется в локальном хранилище браузера (<code>localStorage</code>, ключ <code>yuv_cookie_consent</code>, значение <code>1</code>), после чего загружается Google Tag Manager;</li>
        <li><strong>«Только необходимые»</strong> — согласие на аналитику не даётся (значение <code>0</code>). GTM и вложенные аналитические теги <strong>не загружаются</strong>. Необходимые cookie продолжают работать.</li>
    </ul>
    <p>Баннер показывается только до сохранения выбора. При повторных визитах с тем же браузером и не очищенным хранилищем выбор применяется автоматически: при ранее данном согласии GTM загружается сразу; при отказе — не загружается, баннер не повторяется.</p>
    <p>Если контейнер GTM не настроен, баннер на сайте не отображается, аналитические скрипты Оператором через GTM не подключаются.</p>

